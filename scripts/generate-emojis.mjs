// Copies the website's curated chat emoji set (resources/js/lib/emojis.ts) into src/constants/emojis.ts as plain arrays,
// so the app needs neither the TypeScript source nor a text-segmentation API at run time. Run by `npm run sync:backend`.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const source = readFileSync(join(process.argv[2], 'resources/js/lib/emojis.ts'), 'utf8');
const segmenter = new Intl.Segmenter(undefined, { granularity: 'grapheme' });
const categories = [];

for (const match of source.matchAll(/key:\s*'(\w+)',\s*icon:\s*'([^']+)',\s*emojis:\s*split\(\s*'([^']*)',?\s*\)/g)) {
  const emojis = Array.from(segmenter.segment(match[3]), (part) => part.segment).filter((emoji) => emoji.trim() !== '');
  categories.push({ key: match[1], icon: match[2], emojis });
}

if (categories.length === 0) {
  throw new Error('No emoji categories found in the backend file: did its format change?');
}

writeFileSync(
  'src/constants/emojis.ts',
  `// Generated by scripts/generate-emojis.mjs from the website's curated emoji set. Do not edit by hand.
export type EmojiCategory = { key: string; icon: string; emojis: string[] };

export const EMOJI_CATEGORIES: EmojiCategory[] = ${JSON.stringify(categories, null, 2)};
`,
);
