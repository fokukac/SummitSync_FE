// Turns the website's activity SVGs (Pictogrammers Material Design Icons, one <path> each) into a typed lookup
// for the app: src/constants/activity-icons.ts. Run by `npm run sync:backend`; never edit the output by hand.
import { readdirSync, readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { join } from 'node:path';

const source = join(process.argv[2], 'resources/js/components/icons/activities');
const icons = {};

for (const file of readdirSync(source)
  .filter((name) => name.endsWith('.svg'))
  .sort()) {
  const match = readFileSync(join(source, file), 'utf8').match(/<path[^>]*\sd="([^"]+)"/);

  if (!match) {
    throw new Error(`${file}: expected a single <path d="…">`);
  }

  icons[file.replace(/\.svg$/, '')] = match[1];
}

const body = Object.entries(icons)
  .map(([key, d]) => `  '${key}': '${d}',`)
  .join('\n');

writeFileSync(
  'src/constants/activity-icons.ts',
  `// Generated by scripts/generate-activity-icons.mjs from the backend's SVGs (Pictogrammers Material Design Icons,
// Apache 2.0; see activity-icons.LICENSE.txt). 24x24 viewBox, filled shapes.
export const ACTIVITY_ICON_PATHS: Record<string, string> = {
${body}
};
`,
);
copyFileSync(join(source, 'LICENSE-material-design-icons.txt'), 'src/constants/activity-icons.LICENSE.txt');
